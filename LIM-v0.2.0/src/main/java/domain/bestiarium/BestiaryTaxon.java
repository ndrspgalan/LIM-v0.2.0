package domain.bestiarium;

/**
 *  — taxonomía canónica del Bestiarium.
 * FERAE, ASPIRANT y ANCIENT pueden coexistir en el plano físico; ASPIRANT y ANCIENT
 * disponen canónicamente de CAMBIAFORMAS como superposición de su marca original. TRANSCENDED pertenece al
 * Intersticio, carece de forma física y se manifiesta como fuerza de la naturaleza.
 */
public enum BestiaryTaxon {
    FERAE,
    ASPIRANT,
    ANCIENT,
    TRANSCENDED
}
