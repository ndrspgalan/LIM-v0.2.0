package domain.knowledge;

/**
 *  — internal scientific canon for regeneration, identity, transference,
 * silicic metamorphosis and permanence.
 */
public final class ContinuityScienceDoctrine {
    private ContinuityScienceDoctrine(){}

    public static CanonVisibility visibility(){ return CanonVisibility.INTERNAL_CANON; }

    public static String truth(){
        return """
                La continuidad personal V881 no reside en una sola memoria. El cuerpo conserva historia material y memoria epigenética; el cerebro conserva arquitectura neuronal, hábitos, recuerdos y
                patrones afectivos; el alma aporta una firma de coherencia que mantiene acopladas ambas
                estructuras como un mismo individuo. Ningún componente aislado basta para reconstruir
                completamente a la persona.

                La regeneración frecuencial restaura coherencia respecto del estado inmediatamente anterior
                del organismo. No regresa a una plantilla humana original. Cada ciclo conserva historia,
                adaptación y deriva epigenética, de modo que la longevidad extrema acumula mutabilidad en
                lugar de borrarla.

                El trasvase álmico tampoco reinicia la identidad. Un nuevo soporte debe reconciliar una
                continuidad ya cargada de historia con una arquitectura neuronal y corporal distinta.
                Rechazo, amnesia, fragmentación o destrucción del receptor se vuelven más probables cuanto
                mayor es el enmarañamiento acumulado.

                La regeneración repetida de una biomáquina basada en carbono-12 tiene un horizonte práctico.
                Cerca del milenio, los individuos más antiguos se aproximan a un punto en el que cuerpo,
                cerebro y coherencia álmica ya no pueden mantener indefinidamente una configuración orgánica
                estable. La enorme mutabilidad que permitió sobrevivir termina amenazando la propia continuidad.

                La metamorfosis silícica no es una regeneración superior. Cambia el régimen material: intenta
                estabilizar la configuración alcanzada sobre una matriz menos obligada a reinterpretarse con
                cada restauración. Su finalidad es clausurar la deriva, no rejuvenecer el carbono.

                La permanencia constituye un problema posterior. Una identidad estabilizada puede dejar
                correlaciones y ecos persistentes en estructuras externas, lugares y fenómenos. En ese punto
                la continuidad deja de depender por completo de un cuerpo localizado y empieza a rozar la
                topología del Intersticio.

                Estas disciplinas forman una cadena: regeneración -> deriva epigenética -> arquitectura
                neuronal -> coherencia álmica -> trasvase -> metamorfosis silícica -> permanencia ->
                Intersticio.  distribuye cada tramo entre especialistas distintos para que el conocimiento
                exista institucionalmente sin convertir a un solo NPC en una enciclopedia omnisciente.
                """.strip();
    }
}
