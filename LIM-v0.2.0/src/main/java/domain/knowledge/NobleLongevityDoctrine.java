package domain.knowledge;

/** Complete internal biological/metaphysical truth of the upper nobility. */
public final class NobleLongevityDoctrine {
    private NobleLongevityDoctrine(){}

    public static CanonVisibility visibility(){ return CanonVisibility.INTERNAL_CANON; }

    public static String truth(){
        return """
                La medicina frecuencial noble aprendió a identificar como estados corregibles no sólo
                enfermedades concretas, sino procesos degenerativos acumulativos, incluida la oxidación
                ordinaria asociada al envejecimiento. Su aplicación repetida permite restaurar una y otra
                vez el mismo organismo y producir una apariencia de salud casi imperecedera.

                El organismo humano sigue siendo una biomáquina basada materialmente en carbono-12.
                Cicatrizar y restaurar repetidamente ese mismo bioproducto no equivale a reiniciarlo desde
                una plantilla perfecta. La cicatrización reiterada es altamente mutable: cada nuevo ciclo
                opera sobre una estructura que ya ha atravesado incontables reparaciones. La continuidad
                funcional puede conservarse mientras la continuidad morfológica se desvía.

                Con suficiente repetición aparecen formas corporales grotescas y configuraciones mentales
                igualmente alejadas de la psicología humana ordinaria. No todos los afectados pierden
                racionalidad; algunos conservan educación, memoria, cálculo y autocontrol mientras su escala
                temporal, sus afectos y su relación con vidas mortales dejan de parecer humanas.

                La acumulación de estas continuidades forzadas conmociona el Intersticio. No se trata de un
                castigo moral ni de que un Velo sea "el mundo de los espíritus". El orden material y
                perceptivo de la realidad recibe una cantidad creciente de biomáquinas cuya continuidad ha
                sido prolongada fuera de los ciclos que normalmente estabilizaban su forma. Esa tensión
                altera la trama intersticial y favorece la aparición o inestabilidad de hendiduras des-veladas.

                Un Velo es, por definición, una hendidura del Intersticio. Sus efectos pueden manifestarse
                como tránsito por líneas telúricas o como cambio del filtro mediante el cual se proyecta y
                reconoce la realidad. La conmoción, por tanto, afecta al Intersticio; el Velo es una de sus
                posibles manifestaciones locales.
                """.strip();
    }
}
